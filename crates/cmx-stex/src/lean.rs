//! Lean 4 + Mathlib translation for `cmx stex check` (STEX-DESIGN §3.8, §9).
//!
//! Each stated goal (`wts`, or the claim of a `theorem`/`lemma`/`claim` label) becomes a Lean
//! `theorem`. Declarations and assumptions become binders and hypotheses. Every derived statement
//! becomes `have hN : P := by stex_auto`, where `stex_auto` tries the standard closing tactics.
//! A `-- stex:LINE` marker on each generated line maps Lean errors back to the .stex source.
//! Prose justifications are ignored (spec). `by THEOREM` adds the Mathlib lemma to the attempt.
//! Statements that can't be expressed (integrals, limits, prose) are kept as comments.

use crate::math::M;
use crate::proof::{Fact, vars_of};
use crate::theorems;
use std::collections::BTreeMap;

pub struct LeanOut {
    pub text: String,
    /// (lean line, stex line), 1-based.
    pub line_map: Vec<(u32, u32)>,
    /// Statements skipped (not expressible in Lean): (stex line, reason).
    pub skipped: Vec<(u32, String)>,
    /// Number of `have`/goal obligations generated.
    pub obligations: usize,
}

